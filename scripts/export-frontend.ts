/**
 * Writes the BatteryPassport ABI, local chain ID and deployed address to
 * frontend/src/contract.ts for the React frontend.
 *
 * Run after compiling/deploying:
 *   npx hardhat run scripts/export-frontend.ts
 *
 * Override the address after a redeploy:
 *   $env:BATTERY_PASSPORT_ADDRESS="0x..."; npx hardhat run scripts/export-frontend.ts
 *
 * Reads the compiled artifact only. It does not connect to any network or deploy.
 */
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { artifacts, config } from "hardhat";

const DEFAULT_ADDRESS = "0x5fbdb2315678afecb367f032d93f642f64180aa3";
const CHAIN_ID = 31337;

const address = (process.env.BATTERY_PASSPORT_ADDRESS ?? DEFAULT_ADDRESS).trim();
if (!/^0x[0-9a-fA-F]{40}$/.test(address)) {
  throw new Error(
    `Invalid contract address "${address}". Expected 0x followed by 40 hex characters ` +
      `(check BATTERY_PASSPORT_ADDRESS).`,
  );
}

const artifact = await artifacts.readArtifact("BatteryPassport");

const destination = path.join(config.paths.root, "frontend", "src", "contract.ts");
await mkdir(path.dirname(destination), { recursive: true });

const contents = `// AUTO-GENERATED by scripts/export-frontend.ts. Do not edit by hand.
//
// The address below is only valid for the current local Hardhat node. After
// restarting \`npx hardhat node\` and redeploying, re-run:
//   npx hardhat run scripts/export-frontend.ts
// (set BATTERY_PASSPORT_ADDRESS if the new deployment address differs).

export const BATTERY_PASSPORT_ADDRESS = "${address}" as const;

export const CHAIN_ID = ${CHAIN_ID} as const;

export const BATTERY_PASSPORT_ABI = ${JSON.stringify(artifact.abi, null, 2)} as const;
`;

await writeFile(destination, contents, "utf8");

console.log(`Exported BatteryPassport ABI (${artifact.abi.length} entries)`);
console.log(`Destination: ${destination}`);
console.log(`Address:     ${address}`);
console.log(`Chain ID:    ${CHAIN_ID}`);
