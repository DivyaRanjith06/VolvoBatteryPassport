/**
 * Shared helpers for frontend/src/contract.ts, the single place that records
 * which address the BatteryPassport contract is deployed at.
 *
 * deploy.ts writes it; export-frontend.ts and seed.ts read the address from it
 * (unless BATTERY_PASSPORT_ADDRESS is set), so the dashboard and the scripts
 * can never silently target different deployments.
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { artifacts, config } from "hardhat";

export const CHAIN_ID = 31337;

export const frontendConfigPath = () => path.join(config.paths.root, "frontend", "src", "contract.ts");

export function assertAddress(address: string): `0x${string}` {
  if (!/^0x[0-9a-fA-F]{40}$/.test(address)) {
    throw new Error(
      `Invalid contract address "${address}". Expected 0x followed by 40 hex characters ` +
        `(check BATTERY_PASSPORT_ADDRESS).`,
    );
  }
  return address as `0x${string}`;
}

/** BATTERY_PASSPORT_ADDRESS if set, otherwise the address last written by deploy.ts. */
export async function resolveContractAddress(): Promise<`0x${string}`> {
  const fromEnv = process.env.BATTERY_PASSPORT_ADDRESS?.trim();
  if (fromEnv) return assertAddress(fromEnv);

  let source: string;
  try {
    source = await readFile(frontendConfigPath(), "utf8");
  } catch {
    throw new Error(
      `${frontendConfigPath()} not found. Run scripts/deploy.ts first, or set BATTERY_PASSPORT_ADDRESS.`,
    );
  }
  const match = source.match(/BATTERY_PASSPORT_ADDRESS = "(0x[0-9a-fA-F]{40})"/);
  if (!match) {
    throw new Error(`No address found in ${frontendConfigPath()}. Run scripts/deploy.ts or set BATTERY_PASSPORT_ADDRESS.`);
  }
  return assertAddress(match[1]);
}

export async function writeFrontendConfig(address: `0x${string}`): Promise<{ destination: string; abiEntries: number }> {
  const artifact = await artifacts.readArtifact("BatteryPassport");
  const destination = frontendConfigPath();
  await mkdir(path.dirname(destination), { recursive: true });

  const contents = `// AUTO-GENERATED by scripts/deploy.ts / scripts/export-frontend.ts. Do not edit by hand.
//
// The address below is only valid for the current local Hardhat node. After
// restarting \`npx hardhat node\`, run scripts/deploy.ts again: it rewrites this file.

export const BATTERY_PASSPORT_ADDRESS = "${address}" as const;

export const CHAIN_ID = ${CHAIN_ID} as const;

export const BATTERY_PASSPORT_ABI = ${JSON.stringify(artifact.abi, null, 2)} as const;
`;

  await writeFile(destination, contents, "utf8");
  return { destination, abiEntries: artifact.abi.length };
}
